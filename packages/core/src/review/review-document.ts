/**
 * Reading and writing `log/YYYY-Www.md` — the weekly review, in progress and
 * finished.
 *
 * The same two rules that govern `projects/document.ts` and
 * `weekly/top-three-document.ts`:
 *
 *   1. **Parsing never fails.** An unknown section, prose under a heading, a
 *      hand-written line matching no grammar — all are carried through
 *      untouched and ignored by the reader. A file the app refuses to open is a
 *      file the app has taken hostage.
 *
 *   2. **Writing is surgical.** Only the lines being appended are added;
 *      everything else is reproduced byte for byte, because the vault is
 *      git-tracked and a read that reformats turns every app open into a diff.
 *
 * **On the third copy of section handling.** This module parses `##` sections
 * locally, as `top-three-document.ts` already does beside `projects/document.ts`.
 * The established habit here is a document module per document type, because
 * the semantics differ where it counts — this file has an in-progress marker,
 * per-step sections, and append-within-section writes that neither of the
 * others needs. **This is the third copy: when a fourth document type needs
 * section handling, extract `vault/markdown.ts` from all four at once rather
 * than adding a fifth** (research R11).
 *
 * The three, so a future fourth can find them all: `projects/document.ts`
 * (Feature 3), `weekly/top-three-document.ts` (Feature 4), and this file.
 * `waiting/waiting-document.ts` arrived with this feature and is deliberately
 * **not** a fourth — `waiting.md` has no `##` sections at all, so it shares the
 * two governing rules and none of the mechanism. Count copies of the section
 * code, not document modules.
 *
 * See specs/005-weekly-review-ritual/contracts/review-log-format.md
 */

export const LOG_DIR = "log";

export function reviewPath(week: WeekId): string {
  return `${LOG_DIR}/${week}.md`;
}

// ---------------------------------------------------------------------------
// Headings and grammar
// ---------------------------------------------------------------------------

export const INBOX_HEADING = "Inbox";
export const PROJECTS_HEADING = "Projects";
export const WAITING_HEADING = "Waiting for";
export const TOP_THREE_HEADING = "Top three";
export const NOTE_HEADING = "Note";
/** The provider's name lives in the heading, so attribution survives a grep. */
export const SUMMARY_HEADING_PREFIX = "Summary";

const H2 = /^##\s+(.+?)\s*$/;
const FIELD = /^\s*([A-Za-z][A-Za-z ]*?)\s*:\s?(.*)$/;
const TITLE = /^#\s+(.*)$/;

const DATE = String.raw`\d{4}-\d{2}-\d{2}`;

const INBOX_LINE = new RegExp(`^- (${DATE}) (?:inbox clear|(\\d+) items?, (\\w+), proceeded)$`);
const PROJECT_LINE = new RegExp(`^- (${DATE}) (\\S+) (.+)$`);
const WAITING_ITEM_LINE = new RegExp(
  `^- (${DATE}) @(\\S+) (\\d+)d (followed up|received|left) — (.*)$`,
);
const WAITING_PROJECT_LINE = new RegExp(
  `^- (${DATE}) project (\\S+) (\\d+)d left waiting$`,
);
const FINISHED_LINE = /^- finished: (.*)$/;
const SLIPPED_LINE = /^- slipped: (.*)$/;
const COMMITTED_LINE = /^- committed (\d{4}-W\d{2}): (.*)$/;
const SUMMARY_HEADING = /^Summary \(generated by (.+)\)$/;

// ---------------------------------------------------------------------------
// Locating things
// ---------------------------------------------------------------------------

/** Body range of a `## Heading`, exclusive of the heading itself. */
function sectionRange(
  lines: string[],
  heading: string,
): { head: number; start: number; end: number } | null {
  const head = lines.findIndex((l) => {
    const m = H2.exec(l);
    return m !== null && (m[1] ?? "").toLowerCase() === heading.toLowerCase();
  });
  if (head === -1) return null;

  let end = lines.length;
  for (let i = head + 1; i < lines.length; i++) {
    if (H2.test(lines[i] ?? "")) {
      end = i;
      break;
    }
  }
  return { head, start: head + 1, end };
}

/** The heading text of the first section whose name starts with `prefix`. */
function findHeading(lines: string[], prefix: string): string | null {
  for (const line of lines) {
    const m = H2.exec(line);
    const text = (m?.[1] ?? "").trim();
    if (m && text.toLowerCase().startsWith(prefix.toLowerCase())) return text;
  }
  return null;
}

function sectionLines(lines: string[], heading: string): string[] {
  const range = sectionRange(lines, heading);
  return range ? lines.slice(range.start, range.end) : [];
}

function sectionText(lines: string[], heading: string): string | null {
  const body = sectionLines(lines, heading).join("\n").trim();
  return body.length === 0 ? null : body;
}

function readField(lines: string[], key: string): string | null {
  for (const line of lines) {
    if (H2.test(line)) break;
    const m = FIELD.exec(line);
    if (m && (m[1] ?? "").trim().toLowerCase() === key.toLowerCase()) {
      const value = (m[2] ?? "").trim();
      return value.length === 0 ? null : value;
    }
  }
  return null;
}

// ---------------------------------------------------------------------------
// Creating
