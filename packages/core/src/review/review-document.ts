/** Adds, updates, or removes one preamble `key: value` line. */
export function setPreambleField(content: string, key: string, value: string | null): string {
  const lines = content.split("\n");

  let existing = -1;
  let lastField = -1;
  for (let i = 0; i < lines.length; i++) {
    if (H2.test(lines[i] ?? "")) break;
    const m = FIELD.exec(lines[i] ?? "");
    if (!m) continue;
    lastField = i;
    if ((m[1] ?? "").trim().toLowerCase() === key.toLowerCase() && existing === -1) existing = i;
  }

  if (value === null) {
    if (existing !== -1) lines.splice(existing, 1);
    return lines.join("\n");
  }

  const line = `${key}: ${value}`;
  if (existing !== -1) {
    lines[existing] = line;
  } else if (lastField !== -1) {
    lines.splice(lastField + 1, 0, line);
  } else {
    const title = lines.findIndex((l) => TITLE.test(l));
    lines.splice(title + 1, 0, "", line);
  }
  return lines.join("\n");
}

/**
 * Appends one line to the end of a section's content.
 *
 * "End of content" rather than "end of section": the blank line separating this
 * section from the next is preserved, so appending never eats the spacing a
 * reader relies on, and the diff is exactly one line.
 */
export function appendToSection(content: string, heading: string, line: string): string {
  const lines = content.split("\n");
  const range = sectionRange(lines, heading);
  if (!range) {
    // A hand-edited file that lost the section: put it back rather than
    // dropping the record on the floor.
    const trimmed = [...lines];
    while (trimmed.length > 0 && (trimmed[trimmed.length - 1] ?? "").trim().length === 0) {
      trimmed.pop();
    }
    return [...trimmed, "", `## ${heading}`, "", line, ""].join("\n");
  }

  let at = range.end;
  while (at > range.start && (lines[at - 1] ?? "").trim().length === 0) at -= 1;
  lines.splice(at, 0, line);
  return lines.join("\n");
}

/** Replaces a section's body, creating the section at the end when absent. */
export function setSectionBody(content: string, heading: string, body: string): string {
  const lines = content.split("\n");
  const range = sectionRange(lines, heading);
  const bodyLines = body.split("\n");

  if (!range) {
    const trimmed = [...lines];
    while (trimmed.length > 0 && (trimmed[trimmed.length - 1] ?? "").trim().length === 0) {
      trimmed.pop();
    }
    return [...trimmed, "", `## ${heading}`, "", ...bodyLines, ""].join("\n");
  }

  let end = range.end;
  while (end > range.start && (lines[end - 1] ?? "").trim().length === 0) end -= 1;
  lines.splice(range.start, end - range.start, "", ...bodyLines);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Line rendering — the grammar in contracts/review-log-format.md
// ---------------------------------------------------------------------------

export function renderInboxLine(on: string, count: number, verdict: string): string {
  if (count === 0) return `- ${on} inbox clear`;
  return `- ${on} ${count} item${count === 1 ? "" : "s"}, ${verdict}ed, proceeded`;
}

export function renderProjectLine(
  on: string,
  slug: string,
  action: ProjectReviewAction,
  detail: string | null,
): string {
  const body =
    action === "none"
      ? "no change"
      : action === "status"
        ? `status ${detail ?? ""}`
        : action === "milestone-done"
          ? `milestone done ${detail ?? ""}`
          : action === "next-action"
            ? `next action ${detail ?? "changed"}`
            : `${detail ?? "outcome"} set`;
  return `- ${on} ${slug} ${body}`;
}

export function renderWaitingItemLine(
  on: string,
  owner: string,
  days: number,
  action: WaitingReviewRecord["action"],
  text: string,
): string {
  const word = action === "followed-up" ? "followed up" : action === "received" ? "received" : "left";
  return `- ${on} @${owner} ${days}d ${word} — ${text}`;
}

export function renderWaitingProjectLine(on: string, slug: string, days: number): string {
  return `- ${on} project ${slug} ${days}d left waiting`;
}

export function renderTopThreeLines(record: TopThreeStepRecord): string[] {
  return [
    ...record.finished.map((t) => `- finished: ${t}`),
    ...record.slipped.map((t) => `- slipped: ${t}`),
    ...record.committed.map((t) => `- committed ${record.forWeek ?? ""}: ${t}`),
  ];
}

export function summaryHeadingFor(provider: string): string {
  return `${SUMMARY_HEADING_PREFIX} (generated by ${provider})`;
}
