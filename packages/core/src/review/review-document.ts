/**
 * A new review's file.
 *
 * Every section exists from the start, so a reader always sees the shape of the
 * ritual and an empty section means "nothing recorded here yet" rather than
 * "this file is malformed". `status` comes first because it is what a person
 * opening the file needs to know first.
 */
export function renderNewReview(week: WeekId, started: string): string {
  return [
    `# Weekly review ${week}`,
    "",
    "status: in progress",
    `started: ${started}`,
    "step: inbox",
    "",
    `## ${INBOX_HEADING}`,
    "",
    `## ${PROJECTS_HEADING}`,
    "",
    `## ${WAITING_HEADING}`,
    "",
    `## ${TOP_THREE_HEADING}`,
    "",
    `## ${NOTE_HEADING}`,
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// Reading
// ---------------------------------------------------------------------------

export function parseReview(content: string, week: WeekId): Review {
  const lines = content.split("\n");

  const statusRaw = (readField(lines, "status") ?? "in progress").toLowerCase();
  const summaryHeading = findHeading(lines, SUMMARY_HEADING_PREFIX);

  return {
    week,
    started: readField(lines, "started") ?? "",
    step: readStep(lines),
    // Anything that is not exactly "complete" reads as still in progress. A
    // half-typed status must not present an unfinished review as finished.
    status: statusRaw === "complete" ? "complete" : "in-progress",
    completed: readField(lines, "completed"),
    inbox: parseInboxRecords(sectionLines(lines, INBOX_HEADING))[0] ?? null,
    projects: parseProjectRecords(sectionLines(lines, PROJECTS_HEADING)),
    waiting: parseWaitingRecords(sectionLines(lines, WAITING_HEADING)),
    topThree: parseTopThreeRecord(sectionLines(lines, TOP_THREE_HEADING)),
    note: sectionText(lines, NOTE_HEADING),
    summary: parseSummary(lines, summaryHeading),
  };
}

export function parseReviewSummary(content: string, week: WeekId): ReviewSummary {
  const lines = content.split("\n");
  const statusRaw = (readField(lines, "status") ?? "in progress").toLowerCase();
  return {
    week,
    started: readField(lines, "started") ?? "",
    status: statusRaw === "complete" ? "complete" : "in-progress",
    completed: readField(lines, "completed"),
  };
}

function readStep(lines: string[]): ReviewStepName {
  const raw = (readField(lines, "step") ?? "").trim().toLowerCase();
  return REVIEW_STEPS.find((s) => s === raw) ?? "inbox";
}

function parseInboxRecords(lines: string[]): InboxStepRecord[] {
  const records: InboxStepRecord[] = [];
  for (const line of lines) {
    const m = INBOX_LINE.exec(line);
    if (!m) continue;
    const count = m[2] === undefined ? 0 : Number(m[2]);
    // The line reads "warned" because that is how it reads in English; the
    // verdict is `warn`. Mapped back rather than stored as written, so a record
    // read from the file is the same shape as one just decided — the two were
    // silently different until a round-trip test said so.
    records.push({
      count,
      verdict: m[3] === "blocked" ? "block" : m[3] === "warned" ? "warn" : "allow",
      on: m[1] ?? "",
      raw: line,
    });
  }
  return records;
}

function parseProjectRecords(lines: string[]): ProjectReviewRecord[] {
  const records: ProjectReviewRecord[] = [];
  for (const line of lines) {
    const m = PROJECT_LINE.exec(line);
    if (!m) continue;
    const rest = (m[3] ?? "").trim();
    const { action, detail } = readProjectAction(rest);
    records.push({ slug: m[2] ?? "", action, detail, on: m[1] ?? "", raw: line });
  }
  return records;
}

function readProjectAction(rest: string): { action: ProjectReviewAction; detail: string | null } {
  if (rest === "no change") return { action: "none", detail: null };
  if (rest.startsWith("status ")) return { action: "status", detail: rest.slice("status ".length) };
  if (rest.startsWith("milestone done ")) {
    return { action: "milestone-done", detail: rest.slice("milestone done ".length) };
  }
  if (rest.startsWith("next action ")) {
    return { action: "next-action", detail: rest.slice("next action ".length) };
  }
  // The three structure fixes the walk offers, in one shape. `milestones set`
  // is what adding a milestone to a flagged project records — the same fix, so
  // the same grammar rather than a fourth spelling.
  const structure = /^(outcome|dri|milestones) set$/.exec(rest);
  if (structure) return { action: "structure", detail: structure[1] ?? null };
  // An unrecognised action is still a record that the project was walked. The
  // file is the record, whoever wrote the line.
  return { action: "none", detail: rest };
}

function parseWaitingRecords(lines: string[]): WaitingReviewRecord[] {
  const records: WaitingReviewRecord[] = [];
  for (const line of lines) {
    const project = WAITING_PROJECT_LINE.exec(line);
    if (project) {
      records.push({
        text: "",
        owner: project[2] ?? "",
        days: Number(project[3] ?? 0),
        subject: "project",
        action: "none",
        on: project[1] ?? "",
        raw: line,
      });
      continue;
    }

    const item = WAITING_ITEM_LINE.exec(line);
    if (!item) continue;
    const word = item[4] ?? "left";
    records.push({
      text: item[5] ?? "",
      owner: item[2] ?? "",
      days: Number(item[3] ?? 0),
      subject: "item",
      action: word === "followed up" ? "followed-up" : word === "received" ? "received" : "none",
      on: item[1] ?? "",
      raw: line,
    });
  }
  return records;
}

function parseTopThreeRecord(lines: string[]): TopThreeStepRecord | null {
  const finished: string[] = [];
  const slipped: string[] = [];
  const committed: string[] = [];
  let forWeek: WeekId | null = null;

  for (const line of lines) {
    const f = FINISHED_LINE.exec(line);
    if (f) {
      finished.push(f[1] ?? "");
      continue;
    }
    const s = SLIPPED_LINE.exec(line);
    if (s) {
      slipped.push(s[1] ?? "");
      continue;
    }
    const c = COMMITTED_LINE.exec(line);
    if (c) {
      forWeek = c[1] ?? null;
      committed.push(c[2] ?? "");
    }
  }

  if (finished.length === 0 && slipped.length === 0 && committed.length === 0) return null;
  return { finished, slipped, committed, forWeek };
}

function parseSummary(lines: string[], heading: string | null): AcceptedSummary | null {
  if (heading === null) return null;
  const m = SUMMARY_HEADING.exec(heading);
  const text = sectionText(lines, heading);
  if (text === null) return null;
  return { text, provider: m?.[1] ?? "unknown" };
}

